CREATE TABLE buildings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(240) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE floors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    building_id BIGINT NOT NULL REFERENCES buildings(id),
    level INTEGER NOT NULL,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uq_floor_level UNIQUE (building_id, level)
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    floor_id BIGINT NOT NULL REFERENCES floors(id),
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 200),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_rooms_floor ON rooms(floor_id);

CREATE TABLE room_equipment (
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    equipment VARCHAR(30) NOT NULL,
    PRIMARY KEY (room_id, equipment),
    CONSTRAINT ck_equipment CHECK (
        equipment IN ('DISPLAY', 'VIDEO_CONFERENCING', 'WHITEBOARD', 'PROJECTOR', 'SPEAKERPHONE')
    )
);

CREATE TABLE bookings (
    id UUID PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    owner_username VARCHAR(50) NOT NULL,
    title VARCHAR(120) NOT NULL,
    attendees INTEGER NOT NULL CHECK (attendees BETWEEN 1 AND 200),
    starts_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ends_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    cancelled_at TIMESTAMP(6) WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_booking_interval CHECK (starts_at < ends_at),
    CONSTRAINT ck_booking_cancellation CHECK (
        (status = 'CONFIRMED' AND cancelled_at IS NULL)
        OR (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
    )
);

CREATE INDEX idx_bookings_room_interval ON bookings(room_id, status, starts_at, ends_at);
CREATE INDEX idx_bookings_owner_start ON bookings(owner_username, starts_at);
